let currentLang = "en";

function stored(key, fallback) {
  try { return localStorage.getItem(key) || fallback; } catch { return fallback; }
}

export function initLang() {
  const saved = stored("aqx.lang", "");
  if (saved === "en" || saved === "fa") currentLang = saved;
  // Persian is the product's primary language: it is the default even when the
  // browser is set to another locale. English remains one click away and is
  // remembered once chosen.
  else currentLang = "fa";
  applyLang();
}

export function getLang() { return currentLang; }

export function setLang(lang) {
  currentLang = lang === "fa" ? "fa" : "en";
  try { localStorage.setItem("aqx.lang", currentLang); } catch { /* storage disabled */ }
  applyLang();
  window.dispatchEvent(new CustomEvent("aqx:langchange", { detail: currentLang }));
}

export function toggleLang() { setLang(currentLang === "en" ? "fa" : "en"); }

export function t(key, vars = {}, lang = currentLang) {
  const table = DICT[lang] || DICT.en;
  let text = table[key] ?? DICT.en[key] ?? key;
  for (const [name, value] of Object.entries(vars)) {
    text = text.split(`{${name}}`).join(String(value));
  }
  return text;
}

/** Localised field from a {en, fa} object (e.g. server metadata). */
export function loc(obj, lang = currentLang) {
  if (!obj) return "";
  if (typeof obj === "string") return obj;
  return obj[lang] ?? obj.en ?? "";
}

function applyLang() {
  const root = document.documentElement;
  root.lang = currentLang;
  root.dir = currentLang === "fa" ? "rtl" : "ltr";
  document.title = t("doc.title");
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nAriaLabel));
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  document.querySelectorAll("[data-lang]").forEach((button) => {
    const active = button.dataset.lang === currentLang;
    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", String(active));
  });
}
